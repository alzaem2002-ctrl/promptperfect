#!/bin/bash
# ?? ?????? ????? ??????? ???????? ?? ComfyUI
# ???? ?????? Stable Diffusion, VAE, AnimateDiff

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

HOME_DIR="$(dirname "$(dirname "$(readlink -f "$0")")")"
COMFYUI_DIR="$HOME_DIR/comfyui/ComfyUI"
MODELS_DIR="$COMFYUI_DIR/models"

echo -e "${BLUE}?????????????????????????????????????????${NC}"
echo -e "${GREEN}?? ??? ????? ???????...${NC}"
echo -e "${BLUE}?????????????????????????????????????????${NC}"

# ???? ??????? ?? ???? ??????
download_with_progress() {
    local url=$1
    local output=$2
    local name=$3
    
    echo -e "\n${YELLOW}? ???? ?????: $name${NC}"
    
    if [ -f "$output" ]; then
        echo -e "${YELLOW}??  ????? ????? ??????. ????...${NC}"
        return
    fi
    
    wget --progress=bar:force:noscroll -O "$output" "$url"
    
    if [ $? -eq 0 ]; then
        echo -e "${GREEN}? ?? ????? $name ?????${NC}"
    else
        echo -e "${RED}? ??? ????? $name${NC}"
        return 1
    fi
}

# 1?? ????? Stable Diffusion v1.5
echo -e "\n${BLUE}1??  ????? Stable Diffusion v1.5${NC}"
download_with_progress \
    "https://huggingface.co/runwayml/stable-diffusion-v1-5/resolve/main/v1-5-pruned-emaonly.safetensors" \
    "$MODELS_DIR/checkpoints/v1-5-pruned-emaonly.safetensors" \
    "Stable Diffusion v1.5"

# 2?? ????? VAE
echo -e "\n${BLUE}2??  ????? VAE${NC}"
download_with_progress \
    "https://huggingface.co/stabilityai/sd-vae-ft-mse-original/resolve/main/vae-ft-mse-840000-ema-pruned.safetensors" \
    "$MODELS_DIR/vae/vae-ft-mse-840000-ema-pruned.safetensors" \
    "VAE Model"

# 3?? ????? AnimateDiff
echo -e "\n${BLUE}3??  ????? AnimateDiff${NC}"
download_with_progress \
    "https://huggingface.co/guoyww/animatediff/resolve/main/mm_sd_v15_v2.ckpt" \
    "$MODELS_DIR/animatediff_models/mm_sd_v15_v2.ckpt" \
    "AnimateDiff v2"

# 4?? ?????? ?????? (???????)
echo -e "\n${YELLOW}?? ?? ???? ????? ????? ???????${NC}"
echo "1) Realistic Vision (4GB)"
echo "2) DreamShaper (2GB)"
echo "3) ??????"
echo "4) ?? ?????"
read -p "???? (1-4): " choice

case $choice in
    1|3)
        echo -e "\n${BLUE}????? Realistic Vision...${NC}"
        download_with_progress \
            "https://huggingface.co/SG161222/Realistic_Vision_V5.1_noVAE/resolve/main/Realistic_Vision_V5.1_fp16-no-ema.safetensors" \
            "$MODELS_DIR/checkpoints/realistic_vision_v51.safetensors" \
            "Realistic Vision v5.1"
        ;;
esac

case $choice in
    2|3)
        echo -e "\n${BLUE}????? DreamShaper...${NC}"
        download_with_progress \
            "https://huggingface.co/Lykon/DreamShaper/resolve/main/DreamShaper_8_pruned.safetensors" \
            "$MODELS_DIR/checkpoints/dreamshaper_8.safetensors" \
            "DreamShaper 8"
        ;;
esac

# ???????
echo -e "\n${BLUE}?????????????????????????????????????????${NC}"
echo -e "${GREEN}?? ????? ????? ???? ???????!${NC}"
echo -e "${BLUE}?????????????????????????????????????????${NC}"

# ??? ??????? ?????????
echo -e "\n${YELLOW}?? ??????? ?????????:${NC}"
du -sh "$MODELS_DIR"/*

echo -e "\n${GREEN}? ???? ?????????!${NC}"
