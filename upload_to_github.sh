#!/bin/bash

# GitHub Release Upload Script
# Usage: ./upload_to_github.sh <GITHUB_TOKEN>

GITHUB_TOKEN="${1:-$GITHUB_TOKEN}"
GITHUB_REPO="alzaem2002-ctrl/nursery-management-system-dari-alhanonah-system"
RELEASE_TAG="auto-rebuild-$(date +%Y-%m-%d-%H%M%S)"
RELEASE_NAME="Automated Website Rebuild - $(date '+%Y-%m-%d %H:%M:%S')"
ZIP_FILE="/workspace/site-clone-package.zip"

if [ -z "$GITHUB_TOKEN" ]; then
    echo "? ???: ?? ??? ????? GITHUB_TOKEN"
    echo ""
    echo "?????????:"
    echo "  ./upload_to_github.sh YOUR_GITHUB_TOKEN"
    echo ""
    echo "?? ?? ?????? ????? ??????:"
    echo "  export GITHUB_TOKEN=your_token_here"
    echo "  ./upload_to_github.sh"
    exit 1
fi

echo "?? ??? ??? ????? ??? GitHub Release..."
echo ""
echo "?? ????????: $GITHUB_REPO"
echo "???  ???????: $RELEASE_TAG"
echo "?? ?????: $ZIP_FILE"
echo ""

# Login to gh CLI
echo "$GITHUB_TOKEN" | gh auth login --with-token

# Create release and upload file
echo "?? ????? ??????? ??????..."
gh release create "$RELEASE_TAG" \
    "$ZIP_FILE" \
    --repo "$GITHUB_REPO" \
    --title "$RELEASE_NAME" \
    --notes "## ?? ???? ?????? ????????? ?? Canva

?? ??????? ?????? ?????? ??? ????? Next.js ???? ???????.

### ? ?????????:
- ? ????? Next.js 15 ????
- ? ??? ????? ??????? (RTL)
- ? ???? ??????? (???? ????? CSS? JS)
- ? ????? ??????
- ? Tailwind CSS

### ?? ????? ?????????:
1. ?? ?????? ????? ???????
2. ?? ?????
3. ???: \`npm install\`
4. ???: \`npm run dev\`
5. ????: http://localhost:3000

### ??? ????? ??????:
$(date '+%Y-%m-%d %H:%M:%S')

---
**??? ??????:** ???? ??? ???  
**??????:** https://muqtasr.my.canva.site/m3lem-suliman21436"

if [ $? -eq 0 ]; then
    echo ""
    echo "? ?? ????? ?????!"
    echo ""
    echo "?? ???? ???????:"
    gh release view "$RELEASE_TAG" --repo "$GITHUB_REPO" --web
    
    # Get download URL
    DOWNLOAD_URL=$(gh release view "$RELEASE_TAG" --repo "$GITHUB_REPO" --json assets --jq '.assets[0].url')
    echo ""
    echo "?? ???? ??????? ???????:"
    echo "$DOWNLOAD_URL"
    
    # Save to file
    cat > /workspace/download_link.txt <<EOF
?? ???? ??????? ??????? ??? GitHub:

???????: $RELEASE_TAG
????????: https://github.com/$GITHUB_REPO

???? ???????:
https://github.com/$GITHUB_REPO/releases/tag/$RELEASE_TAG

???? ??????? ???????:
$DOWNLOAD_URL

????? ???????: $(date '+%Y-%m-%d %H:%M:%S')
EOF
    
    echo ""
    echo "?? ?? ??? ????????? ??: download_link.txt"
else
    echo ""
    echo "? ??? ?????!"
    exit 1
fi
